// Exported transaction seam permits real cancellation/race tests without native
// effects. Production dependencies below retain all ownership/admission checks.
export async function runNativeServiceReadTransaction({requestId,signal},d){
 let published=false,phase='prepare',outcome,failure,cleanupPending=false
 const abort=()=>{if(signal?.aborted)throw Error('cancelled')}
 try{
  abort();const prepared=await d.prepare();abort()
  phase='enqueue';published=true;d.enqueue(prepared.request)
  phase='claim'
  if((await d.claim(requestId))?.id!==requestId)throw Error('claim refused')
  phase='revalidate';abort();await d.revalidate();abort()
  phase='send'
  await d.send(); // exactly one invocation; never retry an uncertain transport
  phase='wait'
  while(d.now()<prepared.request.expiresAt){
   abort()
   if(d.responsePresent()){phase='reconcile';outcome=await d.reconcile();break}
   await d.wait()
  }
  if(!outcome)throw Error('result deadline')
 }catch{
  failure=Object.assign(Error('native service read unresolved at '+phase+(published?'; inspect '+requestId:'; no request published')),{category:'native_service_read_unresolved',phase,requestId:published?requestId:null,retrySafe:!published,detail:{phase,requestId:published?requestId:null,retrySafe:!published}})
 }finally{if(published){try{await d.cancel(requestId,'native-service-read-finished')}catch{cleanupPending=true}}}
 if(failure){failure.cleanupPending=cleanupPending;failure.detail.cleanupPending=cleanupPending;throw failure}
 return {...outcome,cleanupPending}
}
export async function nativeServiceRead(serviceId,targetSession,{timeoutMs=20000,signal}={}){
 if(!/^[a-f0-9]{32}$/.test(serviceId)||!/^local_[a-f0-9-]{36}$/.test(targetSession)||!Number.isInteger(timeoutMs)||timeoutMs<1000||timeoutMs>60000)throw Object.assign(Error('invalid native service read arguments'),{category:'bad_args'})
 const requestId='rpeer'+randomUUID().replaceAll('-','')
 return withLock('broker',async()=>{
  let enrollment,pkg,broker,admitted
  function preflight(){
   enrollment=json(root+'native-service-enrollment-'+serviceId+'.json');const {config,epoch,dest,baseline}=enrollment
   pkg=buildNativePeerServicePackage(config)
   if(enrollment.kind!=='service'||config.id!==serviceId||config.brokerCwd!==BROKER_DIR||dest!=='/Users/taylor/.claude/dev-mods/'+config.brokerSession.slice(6)+'/desktop-bridge-native-peer-service')throw Error('enrollment refused')
   if(!baseline||Object.keys(baseline).sort().join(',')!=='.claude/settings.json,stop-rescue-policy.json')throw Error('baseline refused')
   const installedHashes=Object.fromEntries(Object.keys(pkg.hashes).map(p=>[p,readProbeBytes(dest+'/'+p).sha256])),currentBaseline=Object.fromEntries(Object.keys(baseline||{}).map(p=>[p,readProbeBytes(config.brokerCwd+'/'+p).sha256]))
   if(JSON.stringify(pkg.hashes)!==JSON.stringify(enrollment.hashes))throw Error('generated bytes changed')
   broker=brokerInfo();admitted=admitNativeServiceRead({config,epoch,ready:json(config.brokerCwd+'/.native-service-'+serviceId+'.ready.json',4096),broker,versions:versions(),baseline,currentBaseline,hashes:pkg.hashes,installedHashes,controls:{stopped:probePathPresence(BROKER_DIR+'/STOP'),armed:probePathPresence(BROKER_DIR+'/stop-rescue-arm.json'),diagnostic:probePathPresence(BROKER_DIR+'/mechanical-probe.json')},targetSession,now:Date.now(),timeoutMs})
   if(!admitted.admitted||broker.permissionMode!=='bypassPermissions')throw Error('admission refused')
  }
  return runNativeServiceReadTransaction({requestId,signal},{
   prepare:()=>{
    preflight();const policy=json(BROKER_DIR+'/stop-rescue-policy.json');if(readProbeBytes(policy.script,65536).sha256!==policy.sha256)throw Error('policy drift')
    const request={id:requestId,protocol:7,createdAt:new Date().toISOString(),expiresAt:admitted.expiresAt,ops:[{op:admitted.op,args:admitted.args}],nativeEffectAdmissionPolicy:{version:1,handlerSha256:policy.sha256,settingsHash:policy.settingsHash}},observe=observeNativeReceipts(enrollment.config.brokerSession,request)
    if(!observe)throw Error('journal absent');request.nativeObservation=observe.start;return {request}
   },enqueue,claim:id=>pickupPending({requestId:id}),revalidate:preflight,
   send:()=>deliver(broker,enrollment.config.token+' '+requestId,{priority:'now',signal,timeoutMs:Math.min(timeoutMs,5000),onPrepared:meta=>writeFileSync(root+'native-service-send-'+requestId+'.json',JSON.stringify({serviceId,requestId,...meta,at:new Date().toISOString(),retrySafe:false})+'\n',{flag:'wx',mode:0o600})}),
   now:Date.now,responsePresent:()=>probePathPresence(BROKER_DIR+'/.native-service-'+requestId+'.result.json')===true,wait:()=>sleep(100),
   reconcile:async()=>{const result=await reconcileNativeServiceResult(serviceId,requestId),state=inspectRequest(requestId);return {...result,lifecycleState:state.state,retrySafe:false}},cancel:cancelRequest
  })
 },{timeoutMs:5000,signal})
}
